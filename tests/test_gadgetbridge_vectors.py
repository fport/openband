"""Cross-check against vectors produced by Gadgetbridge's own Java code.

tests/vectors/gadgetbridge.json was generated by running the method bodies of HuaweiCrypto,
CheckSums.getCRC16, VarInt and HuaweiPacket.serializeSliced from Gadgetbridge (copied into a
standalone Java file, Android bits removed) on the fixed inputs recorded in each vector.
"""

import json
from pathlib import Path

import pytest

from openband import crypto, frame
from openband.tlv import encode_varint, decode_varint

VECTORS = json.loads((Path(__file__).parent / "vectors" / "gadgetbridge.json").read_text())


def of(kind):
    return [v for v in VECTORS if v["kind"] == kind]


@pytest.mark.parametrize("v", of("digest"), ids=lambda v: f"mode{v['auth_mode']}-v{v['auth_version']}-algo{v['auth_algo']}")
def test_digest(v):
    kw = dict(
        auth_version=v["auth_version"],
        auth_mode=v["auth_mode"],
        auth_algo=v["auth_algo"],
        key=bytes.fromhex(v["key"]) if v["key"] else None,
    )
    nonce = bytes.fromhex(v["nonce"])
    assert crypto.digest_challenge(nonce, **kw).hex() == v["challenge"]
    assert crypto.digest_response(nonce, **kw).hex() == v["response"]


@pytest.mark.parametrize("v", of("mac_key"), ids=lambda v: f"v{v['auth_version']}")
def test_mac_bond_key(v):
    assert crypto.mac_bond_key(v["mac"], v["auth_version"]).hex() == v["key"]


@pytest.mark.parametrize("v", of("aes"), ids=lambda v: "gcm" if v["gcm"] else "cbc")
def test_aes(v):
    key, iv, plain = (bytes.fromhex(v[k]) for k in ("key", "iv", "plain"))
    assert crypto.encrypt(v["gcm"], plain, key, iv).hex() == v["cipher"]
    assert crypto.decrypt(v["gcm"], bytes.fromhex(v["cipher"]), key, iv) == plain


@pytest.mark.parametrize("v", of("crc16"), ids=lambda v: v["data"] or "empty")
def test_crc16(v):
    assert frame.crc16(bytes.fromhex(v["data"])) == v["crc"]


@pytest.mark.parametrize("v", of("varint"), ids=lambda v: str(v["value"]))
def test_varint(v):
    assert encode_varint(v["value"]).hex() == v["bytes"]
    assert decode_varint(bytes.fromhex(v["bytes"]), 0) == (v["value"], len(v["bytes"]) // 2)


@pytest.mark.parametrize("v", of("frame"), ids=lambda v: f"{len(v['body']) // 2}B-slice{v['slice_size']}")
def test_frame_encode_and_reassemble(v):
    body = bytes.fromhex(v["body"])
    packets = frame.encode(v["service"], v["command"], body, v["slice_size"])
    assert [p.hex() for p in packets] == v["packets"]
    msgs = frame.Reassembler().feed(b"".join(packets))
    assert len(msgs) == 1
    assert (msgs[0].service, msgs[0].command, msgs[0].body) == (v["service"], v["command"], body)
